/**
 * Map a normalised pillar slug to its article pool.
 * Slugs are lowercased versions of the pillar name with spaces replaced by dashes.
 */
const PILLAR_ARTICLE_MAP: Record<string, SlmArticle[]> = {
  sleep: SLM_SLEEP_ARTICLES,
  nutrition: SLM_NUTRITION_ARTICLES,
  "stress-management": SLM_STRESS_ARTICLES,
  "cognitive-enhancement": SLM_COGNITIVE_ARTICLES,
  "social-connection": SLM_SOCIAL_ARTICLES,
  movement: SLM_MOVEMENT_ARTICLES,
};

/** Normalise a human-readable pillar name to a slug for lookup. */
function toPillarSlug(name: string): string {
  return name.toLowerCase().trim().replace(/\s+/g, "-");
}

/** Score a single article against the query string. */
function scoreArticle(article: SlmArticle, q: string, words: string[]): number {
  let score = 0;
  for (const topic of article.topics) {
    if (q.includes(topic.toLowerCase())) score += 2;
  }
  for (const word of words) {
    for (const topic of article.topics) {
      if (topic.toLowerCase().includes(word)) score += 1;
    }
  }
  return score;
}

/**
 * Find the single most relevant SLM article for a given query string,
 * filtered to the article pool for `pillarName`.
 *
 * Falls back to the sleep pool when the pillar is unknown so that legacy
 * callers keep working without modification.
 *
 * Returns the best-scoring article, or the first article in the pool when
 * nothing scores above zero (ensures a result is always returned).
 */
export function findRelevantArticleForPillar(
  query: string,
  pillarName: string,
): SlmArticle {
  const slug = toPillarSlug(pillarName);
  const pool = PILLAR_ARTICLE_MAP[slug] ?? SLM_SLEEP_ARTICLES;

  const q = query.toLowerCase();
  const words = q.split(/\W+/).filter(w => w.length > 2);

  let best: SlmArticle = pool[0];
  let bestScore = 0;

  for (const article of pool) {
    const score = scoreArticle(article, q, words);
    if (score > bestScore) {
      bestScore = score;
      best = article;
    }
  }

  return best;
}

/**
 * Find the single most relevant SLM article for a given query string.
 * Returns null if no article scores above the minimum threshold.
 * @deprecated Prefer `findRelevantArticleForPillar` which scopes to the right pillar.
 */
export function findRelevantArticle(query: string): SlmArticle | null {
  const q = query.toLowerCase();
  const words = q.split(/\W+/).filter(w => w.length > 2);

  let best: SlmArticle | null = null;
  let bestScore = 0;

  for (const article of SLM_SLEEP_ARTICLES) {
    let score = 0;
    for (const topic of article.topics) {
      if (q.includes(topic.toLowerCase())) score += 2;
    }
    for (const word of words) {
      for (const topic of article.topics) {
        if (topic.toLowerCase().includes(word)) score += 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = article;
    }
  }

  // Minimum score of 1 to return a result; otherwise pick a general fallback
  if (bestScore < 1) {
    // Default: the practical tips article — universally relevant
    return SLM_SLEEP_ARTICLES[0];
  }
  return best;
}

